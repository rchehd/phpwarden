const template = `# Generated by phpwarden init; see README "Configure a project".
version: 1
profile: drupal
%sphp:
  runtime: %q  # from %s
  target:
    min: %q  # from %s
    max: %q
`

type Options struct {
	CWD          string
	Project      string
	ComposerRoot string
	Runtime      string
	Target       string
	PreCommit    bool
	Executable   string
}

type Choice struct {
	Version string `json:"version"`
	Source  string `json:"source"`
}

type NativeConfig struct {
	Checker string `json:"checker"`
	Path    string `json:"path"`
}

type Result struct {
	Created       bool                  `json:"created"`
	Location      config.Location       `json:"location"`
	ComposerRoot  string                `json:"composer_root,omitempty"`
	Runtime       *Choice               `json:"runtime,omitempty"`
	Target        *Choice               `json:"target,omitempty"`
	Image         string                `json:"image,omitempty"`
	Project       *profile.Facts        `json:"project,omitempty"`
	Base          *string               `json:"base,omitempty"`
	NativeConfigs []NativeConfig        `json:"native_configs,omitempty"`
	PreCommit     *githook.Installation `json:"pre_commit,omitempty"`
}

// Run writes a minimal configuration for the Drupal project, or validates the one already there.
func Run(ctx context.Context, options Options) (Result, error) {
	root, err := projectRoot(ctx, options)
	if err != nil {
		return Result{}, err
	}
	var hook githook.Plan
	if options.PreCommit {
		hook, err = githook.PrepareInstall(ctx, root, options.Executable)
		if err != nil {
			return Result{}, err
		}
	}
	result, err := configure(ctx, root, options)
	if err != nil || !options.PreCommit {
		return result, err
	}
	installed, err := hook.Install()
	if err != nil {
		return result, fmt.Errorf("configuration is ready, but pre-commit installation failed: %w", err)
	}
	result.PreCommit = &installed
	return result, nil
}

func configure(ctx context.Context, root string, options Options) (Result, error) {
	location := config.Location{Root: root, Path: filepath.Join(root, config.Filename)}
	result := Result{Location: location}
	if _, err := os.Lstat(location.Path); err == nil {
		return result, validateExisting(root)
	} else if !os.IsNotExist(err) {
		return result, err
	}
	composerRoot, err := findComposerRoot(root, options)
	if err != nil {
		return result, err
	}
	facts, err := drupal.DiscoverIn(root, composerRoot)
	if err != nil {
		return result, fmt.Errorf("discover Drupal project: %w", err)
	}
	if facts.Version == nil && facts.WebRoot == nil {
		return result, fmt.Errorf("%s is not a Drupal project: composer.lock has no drupal/core and no web root was found; pass --project PATH or --composer-root DIR", filepath.Join(root, composerRoot))
	}
	data, runtime, target, selection, err := choose(location, composerRoot, facts, options)
	if err != nil {
		return result, err
	}
	if err := write(location.Path, data); errors.Is(err, fs.ErrExist) {
		return result, validateExisting(root)
	} else if err != nil {
		return result, fmt.Errorf("write %s: %w", config.Filename, err)
	}
	result.Created, result.Runtime, result.Target, result.Image, result.Project = true, &runtime, &target, selection.Image, &facts
	if composerRoot != "." {
		result.ComposerRoot = composerRoot
	}
	if base, err := git(ctx, root, "symbolic-ref", "--quiet", "--short", "refs/remotes/origin/HEAD"); err == nil {
		result.Base = &base
	}
	for _, tool := range []struct {
		checker    string
		candidates []string
	}{{"phpcs", phpcs.ConfigCandidates}, {"phpmd", phpmd.ConfigCandidates}, {"phpstan", phpstan.ConfigCandidates}, {"twig-cs-fixer", twigcsfixer.ConfigCandidates}, {"semgrep", semgrep.ConfigCandidates}, {"rector", rector.ConfigCandidates}, {"deptrac", deptrac.ConfigCandidates}, {"composer-require-checker", packagecheck.Candidates("composer-require-checker")}, {"composer-unused", packagecheck.Candidates("composer-unused")}} {
		for _, name := range append(slices.Clone(tool.candidates), prefixed(composerRoot, tool.candidates)...) {
			if info, err := os.Lstat(filepath.Join(root, filepath.FromSlash(name))); err == nil && info.Mode().IsRegular() {
				result.NativeConfigs = append(result.NativeConfigs, NativeConfig{Checker: tool.checker, Path: name})
				break
			}
		}
	}
	for _, id := range []string{"eslint", "stylelint", "jscpd"} {
		if name, err := nodecheck.DiscoverConfig(root, composerRoot, id); err == nil && name != "" {
			result.NativeConfigs = append(result.NativeConfigs, NativeConfig{Checker: id, Path: name})
		}
	}
	if name, err := gitleaks.DiscoverConfig(root, composerRoot); err == nil && name != "" {
		result.NativeConfigs = append(result.NativeConfigs, NativeConfig{Checker: "gitleaks", Path: name})
	}
	return result, nil
}

func prefixed(composerRoot string, names []string) []string {
	if composerRoot == "." {
		return nil
	}
	result := make([]string, len(names))
	for i, name := range names {
		result[i] = path.Join(composerRoot, name)
	}
	return result
}

func choose(location config.Location, composerRoot string, facts profile.Facts, options Options) ([]byte, Choice, Choice, toolset.Selection, error) {
	runtime, err := detectRuntime(location.Root, composerRoot, facts, options.Runtime)
	if err != nil {
		return nil, Choice{}, Choice{}, toolset.Selection{}, err
	}
	target := func(runtime Choice) Choice {
		if options.Target != "" {
			return Choice{options.Target, "--php-target"}
		}
		if facts.PlatformPHP != nil {
			return Choice{minor(*facts.PlatformPHP), path.Join(composerRoot, "composer.json") + " config.platform.php"}
		}
		return Choice{runtime.Version, "php.runtime"}
	}
	runtimes, err := toolset.Runtimes("drupal")
	if err != nil {
		return nil, Choice{}, Choice{}, toolset.Selection{}, err
	}
	if runtime != nil {
		data, selection, err := generate(location, composerRoot, *runtime, target(*runtime))
		if err == nil {
			return data, *runtime, target(*runtime), selection, nil
		}
		hint := "pass --php-runtime and --php-target to choose other versions"
		var fits []string
		for _, version := range runtimes {
			candidate := Choice{version, "--php-runtime"}
			if _, _, err := generate(location, composerRoot, candidate, target(candidate)); err == nil {
				fits = append(fits, version)
			}
		}
		if len(fits) > 0 && options.Runtime != fits[0] {
			hint = fmt.Sprintf("the project's Composer requirements fit runtime %s; pass --php-runtime %s", strings.Join(fits, ", "), fits[0])
		}
		return nil, Choice{}, Choice{}, selection, fmt.Errorf("PHP runtime %s (from %s), target %s (from %s): %w; %s",
			runtime.Version, runtime.Source, target(*runtime).Version, target(*runtime).Source, err, hint)
	}
	var failures []string
	for _, version := range runtimes {
		candidate := Choice{version, "composer.lock, the lowest supported PHP all packages allow"}
		data, selection, err := generate(location, composerRoot, candidate, target(candidate))
		if err == nil {
			return data, candidate, target(candidate), selection, nil
		}
		failures = append(failures, version+": "+err.Error())
	}
	return nil, Choice{}, Choice{}, toolset.Selection{}, fmt.Errorf("no PHP version found in .ddev or composer.json config.platform.php, and no supported runtime %s satisfies the Composer requirements (%s); pass --php-runtime and --php-target",
		strings.Join(runtimes, ", "), strings.Join(failures, "; "))
}

// generate renders the configuration and checks it the same way check does, without Docker.
func generate(location config.Location, composerRoot string, runtime, target Choice) ([]byte, toolset.Selection, error) {
	root := ""
	if composerRoot != "." {
		root = fmt.Sprintf("composer_root: %q  # directory with composer.json\n", composerRoot)
	}
	data := fmt.Appendf(nil, template, root, runtime.Version, runtime.Source, target.Version, target.Source, target.Version)
	effective, err := config.Parse(data)
	if err != nil {
		return nil, toolset.Selection{}, err
	}
	effective, err = discovery.Apply(location, effective)
	if err != nil {
		return nil, toolset.Selection{}, err
	}
	selection, err := toolset.Resolve(effective)
	return data, selection, err
}

func validateExisting(root string) error {
	location, err := config.Resolve(config.LocationOptions{CWD: root, Project: root})
	if err == nil {
		_, err = config.Load(location)
	}
	if err != nil {
		return fmt.Errorf("existing %s is invalid: %w; fix it, or remove it to generate a new one", config.Filename, err)
	}
	return nil
}

// write creates the file only if it does not exist yet, so concurrent runs cannot overwrite each other.
func write(filename string, data []byte) error {
	file, err := os.CreateTemp(filepath.Dir(filename), config.Filename+".*.tmp")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	_, err = file.Write(data)
	if err == nil {
		err = file.Chmod(0o644)
	}
	if err == nil {
		err = file.Sync()
	}
	if closeErr := file.Close(); err == nil {
		err = closeErr
	}
	if err != nil {
		return err
	}
	return os.Link(file.Name(), filename)
}
